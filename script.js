/* ——— Reviews carousel ——— */
function initReviewsCarousel() {
  const root = document.querySelector("[data-reviews-carousel]");
  const track = document.querySelector("[data-reviews-track]");
  const prevBtn = document.querySelector("[data-reviews-prev]");
  const nextBtn = document.querySelector("[data-reviews-next]");
  if (!root || !track || !prevBtn || !nextBtn) return;

  const cards = Array.from(track.children);
  if (!cards.length) return;

  let index = 0;
  let animating = false;
  let visibleCount = 3;

  function readVisibleCount() {
    const slider = root.querySelector(".reviews__slider");
    if (!slider) return 1;
    const raw = getComputedStyle(slider).getPropertyValue("--reviews-visible").trim();
    const parsed = Number.parseInt(raw, 10);
    return Number.isFinite(parsed) && parsed > 0 ? parsed : 1;
  }

  function maxIndex() {
    return Math.max(0, cards.length - visibleCount);
  }

  function stepWidth() {
    const card = track.querySelector(".reviews__card");
    if (!card) return 0;
    const gap =
      parseFloat(getComputedStyle(track).columnGap || getComputedStyle(track).gap) || 0;
    return card.getBoundingClientRect().width + gap;
  }

  function setOffset(nextIndex, animate) {
    const x = stepWidth() * nextIndex;
    track.style.transition =
      animate && !reduceMotion ? `transform ${FADE_MS}ms ease` : "none";
    track.style.transform = `translateX(-${x}px)`;
  }

  function updateNav() {
    const atStart = index <= 0;
    const atEnd = index >= maxIndex();
    prevBtn.disabled = atStart;
    nextBtn.disabled = atEnd;
  }

  function goTo(nextIndex, animate = true) {
    const clamped = Math.min(Math.max(nextIndex, 0), maxIndex());
    if (clamped === index) {
      updateNav();
      return;
    }
    if (animating && animate && !reduceMotion) return;

    index = clamped;
    updateNav();

    if (!animate || reduceMotion) {
      setOffset(index, false);
      return;
    }

    animating = true;
    setOffset(index, true);
    window.setTimeout(() => {
      animating = false;
    }, FADE_MS);
  }

  function refresh() {
    visibleCount = readVisibleCount();
    if (index > maxIndex()) index = maxIndex();
    setOffset(index, false);
    updateNav();
  }

  prevBtn.addEventListener("click", () => goTo(index - 1, true));
  nextBtn.addEventListener("click", () => goTo(index + 1, true));

  root.addEventListener("keydown", (event) => {
    if (event.key === "ArrowLeft") {
      event.preventDefault();
      goTo(index - 1, true);
    } else if (event.key === "ArrowRight") {
      event.preventDefault();
      goTo(index + 1, true);
    }
  });

  let touchStartX = null;
  root.addEventListener(
    "touchstart",
    (event) => {
      touchStartX = event.changedTouches[0]?.clientX ?? null;
    },
    { passive: true }
  );
  root.addEventListener(
    "touchend",
    (event) => {
      if (touchStartX == null) return;
      const endX = event.changedTouches[0]?.clientX ?? touchStartX;
      const delta = endX - touchStartX;
      touchStartX = null;
      if (Math.abs(delta) < 40) return;
      if (delta > 0) goTo(index - 1, true);
      else goTo(index + 1, true);
    },
    { passive: true }
  );

  window.addEventListener("resize", refresh);
  refresh();
}

initReviewsCarousel();

/* ——— Scroll reveal ——— */
function initScrollReveal() {
  const targets = document.querySelectorAll(
    [
      ".mission__inner > h2",
      ".mission__card",
      ".works__inner > h2",
      ".works__card",
      ".services__inner > h2",
      ".services__tabs",
      ".services__panels",
      ".pricing__inner > h2",
      ".pricing__tabs",
      ".pricing__panels",
      ".offer__copy",
      ".offer__form",
      ".clients__inner > h2",
      ".clients__slider",
      ".reviews__inner > h2",
      ".reviews__carousel",
      ".about__inner > h2",
      ".about__copy",
      ".about__brand",
      ".contact__inner > h2",
      ".contact__info",
      ".contact__panel",
    ].join(", ")
  );

  if (!targets.length) return;

  if (reduceMotion) {
    targets.forEach((el) => el.classList.add("is-inview"));
    return;
  }

  const groups = new Map();

  targets.forEach((el) => {
    el.setAttribute("data-reveal", "");
    const groupRoot =
      el.closest("section") || el.closest(".about-block") || el.parentElement;
    if (!groups.has(groupRoot)) groups.set(groupRoot, []);
    groups.get(groupRoot).push(el);
  });

  groups.forEach((els) => {
    els.forEach((el, index) => {
      el.style.setProperty("--reveal-delay", `${Math.min(index, 5) * 50}ms`);
    });
  });

  const reveal = (el) => el.classList.add("is-inview");

  if (!("IntersectionObserver" in window)) {
    targets.forEach(reveal);
    return;
  }

  const observer = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        reveal(entry.target);
        observer.unobserve(entry.target);
      });
    },
    { threshold: 0.14, rootMargin: "0px 0px -8% 0px" }
  );

  targets.forEach((el) => observer.observe(el));
}

initScrollReveal();
