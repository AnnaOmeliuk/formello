let isSwitching = false;
let isModalAnimating = false;
let isViewSwitching = false;
let currentLang = "uk";
let lastFocused = null;

function t() {
  return translations[currentLang];
}

function setTexts(lang) {
  const dict = translations[lang];
  if (!dict) return;

  currentLang = lang;
  document.documentElement.lang = dict.htmlLang;
  document.title = dict.title;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (key && dict[key] != null) el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (key && dict[key] != null) el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (key && dict[key] != null) el.setAttribute("aria-label", dict[key]);
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key && dict[key] != null) el.setAttribute("placeholder", dict[key]);
  });

  if (langCode) langCode.textContent = dict.code;
  if (langButton) {
    langButton.dataset.lang = lang;
    langButton.setAttribute("aria-label", dict.langAria);
  }
  syncNavToggleLabel();

  refreshVisibleErrors();

  try {
    localStorage.setItem("formello-lang", lang);
  } catch (_) {
    /* ignore */
  }
}

function applyLanguage(lang, { animate = false } = {}) {
  if (!translations[lang]) return;

  if (!animate || reduceMotion) {
    setTexts(lang);
    return;
  }

  if (isSwitching) return;
  isSwitching = true;
  document.body.classList.add("is-lang-fading");

  window.setTimeout(() => {
    setTexts(lang);
    document.body.classList.remove("is-lang-fading");
    isSwitching = false;
  }, FADE_MS);
}

function toggleLanguage() {
  const next = langButton?.dataset.lang === "en" ? "uk" : "en";
  applyLanguage(next, { animate: true });
}

function clearFieldErrors() {
  form?.querySelectorAll(".field").forEach((field) => {
    field.classList.remove("is-invalid");
    const error = field.querySelector(".field__error");
    if (error) {
      error.hidden = true;
      error.textContent = "";
    }
  });
}

function setFieldError(name, message) {
  const input = form?.elements.namedItem(name);
  if (!input || !("closest" in input)) return;
  const field = input.closest(".field");
  const error = field?.querySelector(`[data-error-for="${name}"]`);
  if (!field || !error) return;
  field.classList.add("is-invalid");
  error.hidden = false;
  error.textContent = message;
}

function validateForm() {
  const dict = t();
  const values = {
    name: String(form.name.value || "").trim(),
    email: String(form.email.value || "").trim(),
    phone: String(form.phone.value || "").trim(),
    message: String(form.message.value || "").trim(),
  };

  clearFieldErrors();
  const errors = {};

  if (!values.name) errors.name = dict.errNameRequired;
  else if (values.name.length < 2) errors.name = dict.errNameShort;

  if (!values.email) errors.email = dict.errEmailRequired;
  else if (!EMAIL_RE.test(values.email)) errors.email = dict.errEmailInvalid;

  if (!values.phone) errors.phone = dict.errPhoneRequired;
  else if (!PHONE_RE.test(values.phone)) errors.phone = dict.errPhoneInvalid;

  if (!values.message) errors.message = dict.errMessageRequired;
  else if (values.message.length < 10) errors.message = dict.errMessageShort;

  Object.entries(errors).forEach(([name, message]) => setFieldError(name, message));
  return { ok: Object.keys(errors).length === 0, values, errors };
}

function refreshVisibleErrors() {
  if (form) {
    const hasVisibleErrors = [...form.querySelectorAll(".field.is-invalid")].length > 0;
    if (hasVisibleErrors) validateForm();
  }

  if (offerForm) {
    const hasOfferErrors = [...offerForm.querySelectorAll(".offer__field.is-invalid")].length > 0;
    if (hasOfferErrors) validateOfferForm();
  }

  if (contactForm) {
    const hasContactErrors = [
      ...contactForm.querySelectorAll(".contact__field.is-invalid"),
    ].length > 0;
    if (hasContactErrors) validateContactForm();
  }
}

function showFormView() {
  if (!formView || !successView) return;
  formView.classList.remove("is-fading-out", "is-fading-in");
  successView.classList.remove("is-fading-out", "is-fading-in");
  successView.hidden = true;
  formView.hidden = false;
}

function showSuccessView({ animate = true } = {}) {
  if (!formView || !successView || isViewSwitching) return;

  if (!animate || reduceMotion) {
    formView.hidden = true;
    successView.hidden = false;
    formView.classList.remove("is-fading-out", "is-fading-in");
    successView.classList.remove("is-fading-out", "is-fading-in");
    return;
  }

  isViewSwitching = true;
  formView.classList.add("is-fading-out");

  window.setTimeout(() => {
    formView.hidden = true;
    formView.classList.remove("is-fading-out");

    successView.hidden = false;
    successView.classList.add("is-fading-in");

    requestAnimationFrame(() => {
      requestAnimationFrame(() => {
        successView.classList.remove("is-fading-in");
      });
    });

    window.setTimeout(() => {
      isViewSwitching = false;
      successView.querySelector("[data-close-request]")?.focus();
    }, FADE_MS);
  }, FADE_MS);
}

function getScrollbarWidth() {
  return Math.max(0, window.innerWidth - document.documentElement.clientWidth);
}

function lockPageScroll() {
  const scrollbarWidth = getScrollbarWidth();
  document.documentElement.style.setProperty("--scrollbar-comp", `${scrollbarWidth}px`);
  document.body.classList.add("is-modal-open");
}

function unlockPageScroll() {
  document.body.classList.remove("is-modal-open");
  if (!document.body.classList.contains("is-nav-open")) {
    document.documentElement.style.removeProperty("--scrollbar-comp");
  }
}

function isNavOpen() {
  return document.body.classList.contains("is-nav-open");
}

function syncNavToggleLabel() {
  if (!navToggle) return;
  const dict = t();
  const key = isNavOpen() ? "menuCloseAria" : "menuOpenAria";
  navToggle.setAttribute("aria-label", dict[key]);
  navToggle.setAttribute("data-i18n-aria", key);
}

function openNav() {
  if (!nav || !navToggle || isNavOpen()) return;

  if (!document.body.classList.contains("is-modal-open")) {
    const scrollbarWidth = getScrollbarWidth();
    document.documentElement.style.setProperty("--scrollbar-comp", `${scrollbarWidth}px`);
  }

  document.body.classList.add("is-nav-open");
  navToggle.setAttribute("aria-expanded", "true");
  if (navBackdrop) navBackdrop.setAttribute("aria-hidden", "false");
  syncNavToggleLabel();
}

function closeNav() {
  if (!nav || !navToggle || !isNavOpen()) return;

  document.body.classList.remove("is-nav-open");
  navToggle.setAttribute("aria-expanded", "false");
  if (navBackdrop) navBackdrop.setAttribute("aria-hidden", "true");
  syncNavToggleLabel();

  if (!document.body.classList.contains("is-modal-open")) {
    document.documentElement.style.removeProperty("--scrollbar-comp");
  }
}

function toggleNav() {
  if (isNavOpen()) closeNav();
  else openNav();
}

function openModal() {
  if (!modal || isModalAnimating || modal.classList.contains("is-open")) return;

  lastFocused = document.activeElement;
  showFormView();
  clearFieldErrors();
  form?.reset();

  modal.hidden = false;
  modal.setAttribute("aria-hidden", "false");
  lockPageScroll();

  if (reduceMotion) {
    modal.classList.add("is-open");
    form?.elements.namedItem("name")?.focus();
    return;
  }

  isModalAnimating = true;
  requestAnimationFrame(() => {
    modal.classList.add("is-open");
    window.setTimeout(() => {
      isModalAnimating = false;
      form?.elements.namedItem("name")?.focus();
    }, MODAL_MS);
  });
}

function closeModal() {
  if (!modal || isModalAnimating || modal.hidden) return;

  const finish = () => {
    modal.classList.remove("is-open");
    modal.hidden = true;
    modal.setAttribute("aria-hidden", "true");
    unlockPageScroll();
    showFormView();
    clearFieldErrors();
    form?.reset();
    isModalAnimating = false;
    if (lastFocused && typeof lastFocused.focus === "function") lastFocused.focus();
  };

  if (reduceMotion) {
    finish();
    return;
  }

  isModalAnimating = true;
  modal.classList.remove("is-open");
  window.setTimeout(finish, MODAL_MS);
}

function onSubmit(event) {
  event.preventDefault();
  if (isViewSwitching) return;

  const result = validateForm();
  if (!result.ok) {
    const firstInvalid = form.querySelector(".field.is-invalid input, .field.is-invalid textarea");
    firstInvalid?.focus();
    return;
  }

  showSuccessView({ animate: true });
}

const servicesSection = document.getElementById("services");
const servicesTabs = servicesSection
  ? [...servicesSection.querySelectorAll("[data-services-tab]")]
  : [];
const servicesPanels = servicesSection
  ? [...servicesSection.querySelectorAll("[data-services-panel]")]
  : [];
let isServicesSwitching = false;

function setServicesTab(nextId, { animate = true } = {}) {
  const nextTab = servicesTabs.find((tab) => tab.dataset.servicesTab === nextId);
  const nextPanel = servicesPanels.find((panel) => panel.dataset.servicesPanel === nextId);
  const currentPanel = servicesPanels.find((panel) => !panel.hidden);

  if (!nextTab || !nextPanel || nextPanel === currentPanel || isServicesSwitching) return;

  servicesTabs.forEach((tab) => {
    const active = tab === nextTab;
    tab.classList.toggle("is-active", active);
    tab.setAttribute("aria-selected", active ? "true" : "false");
    tab.tabIndex = active ? 0 : -1;
  });

  const swap = () => {
    if (currentPanel) currentPanel.hidden = true;
    nextPanel.hidden = false;
  };

  if (!animate || reduceMotion || !currentPanel) {
    if (currentPanel) {
      currentPanel.classList.remove("is-fading-out", "is-fading-in");
    }
    nextPanel.classList.remove("is-fading-out", "is-fading-in");
    swap();
    return;
  }

  isServicesSwitching = true;
  currentPanel.classList.add("is-fading-out");

  window.setTimeout(() => {
    currentPanel.hidden = true;
    currentPanel.classList.remove("is-fading-out");

    nextPanel.hidden = false;
    nextPanel.classList.add("is-fading-in");

    requestAnimationFrame(() => {
      requestAnimationFrame(() => {
        nextPanel.classList.remove("is-fading-in");
      });
    });

    window.setTimeout(() => {
      isServicesSwitching = false;
    }, FADE_MS);
  }, FADE_MS);
}

servicesTabs.forEach((tab) => {
  tab.addEventListener("click", () => {
    setServicesTab(tab.dataset.servicesTab, { animate: true });
  });

  tab.addEventListener("keydown", (event) => {
    const index = servicesTabs.indexOf(tab);
    if (index < 0) return;

    let nextIndex = -1;
    if (event.key === "ArrowRight" || event.key === "ArrowDown") {
      nextIndex = (index + 1) % servicesTabs.length;
    } else if (event.key === "ArrowLeft" || event.key === "ArrowUp") {
      nextIndex = (index - 1 + servicesTabs.length) % servicesTabs.length;
    } else if (event.key === "Home") {
      nextIndex = 0;
    } else if (event.key === "End") {
      nextIndex = servicesTabs.length - 1;
    }

    if (nextIndex < 0) return;
    event.preventDefault();
    const nextTab = servicesTabs[nextIndex];
    setServicesTab(nextTab.dataset.servicesTab, { animate: true });
    nextTab.focus();
  });
});

